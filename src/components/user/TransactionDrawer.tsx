"use client";

import { ChipScroller } from "@/components/ui/ChipScroller";
import React, { useState, useMemo, useEffect, useRef } from "react";
import { Drawer } from "vaul";
import { motion } from "framer-motion";
import { Trash2, X } from "@/components/illustrations/UiGlyphs";
import { useBukuDompetStore } from "@/store/useBukuDompetStore";
import { pickViewedChild } from "@/lib/active-child";
import {
  EXPENSE_CATEGORIES,
  INCOME_CATEGORIES,
  parseSmartQuickSplit,
  validateItemizedCombo,
} from "@/lib/spending-detective";
import { CozyIcon, CategoryIcon } from "@/components/illustrations/CozyIcons";
import {
  CustomizablePetAvatar,
  GROWTH_STAGE_META,
  type PetMood,
} from "@/components/illustrations/PetAvatarSystem";
import {
  TactileButton,
  ChunkyProgressBar,
  formatRupiah,
} from "@/components/ui/CozyPrimitives";
import { soundEffects, fireCozyConfetti } from "@/lib/sound-effects";
import { cn, formatCompactRupiah } from "@/lib/utils";

const QUICK_PRICE_CHIPS = [2000, 5000, 10000, 15000, 25000];

export function TransactionDrawer() {
  const {
    isTransactionDrawerOpen,
    setTransactionDrawerOpen,
    activeProfileId,
    currentRole,
    monitoredUserId,
    profiles,
    addTransaction,
  } = useBukuDompetStore();

  const userProfile = pickViewedChild({ currentRole, activeProfileId, monitoredUserId, profiles });

  const currentStage = userProfile.currentStage || 1;
  const petName = userProfile.petCustomName || "Mochi";

  const [txType, setTxType] = useState<"expense" | "income">("expense");
  const [inputMode, setInputMode] = useState<"detailed" | "quick">("detailed");
  const [category, setCategory] = useState<string>(EXPENSE_CATEGORIES[0].name);
  const [customTitle, setCustomTitle] = useState<string>("");
  const [quickAmount, setQuickAmount] = useState<string>("");
  const [activeRowIdx, setActiveRowIdx] = useState<number>(0);

  // Smart Quick-Split Bar
  const [smartSplitInput, setSmartSplitInput] = useState<string>("");

  // Itemized rows (Default in Misi Rinci)
  const [items, setItems] = useState<
    { item_name: string; quantity: number; unit_price: number }[]
  >([
    { item_name: "Nasi Goreng Spesial", quantity: 1, unit_price: 18000 },
    { item_name: "Es Teh Manis", quantity: 1, unit_price: 5000 },
  ]);

  const handleApplySmartSplit = (rawText: string) => {
    setSmartSplitInput(rawText);
    const parsed = parseSmartQuickSplit(rawText);
    if (parsed.length > 0) {
      setItems(
        parsed.map((p) => ({
          item_name: p.item_name,
          quantity: p.quantity,
          unit_price: p.unit_price,
        }))
      );
      soundEffects.comboStepNote(parsed.length);
    }
  };

  const itemizedTotal = useMemo(() => {
    return items.reduce(
      (sum, it) =>
        sum + (Number(it.quantity) || 1) * (Number(it.unit_price) || 0),
      0
    );
  }, [items]);

  // Auto-calculated title from items when in Detailed Mode
  const autoGeneratedTitle = useMemo(() => {
    const validNames = items
      .map((i) => i.item_name.trim())
      .filter((n) => n.length > 0);
    if (validNames.length === 0) return category;
    if (validNames.length <= 2) return validNames.join(" & ");
    return `${validNames[0]}, ${validNames[1]} (+${validNames.length - 2} lainnya)`;
  }, [items, category]);

  const comboStatus = useMemo(() => {
    if (inputMode === "quick" || txType === "income") {
      return {
        isValidCombo: false,
        validItemsCount: 0,
        pointsPreview: 5,
        xpPreview: 10,
      };
    }
    return validateItemizedCombo(items);
  }, [items, inputMode, txType]);

  // Play ascending combo note when validItemsCount increases
  const prevValidCountRef = useRef<number>(comboStatus.validItemsCount);
  useEffect(() => {
    if (comboStatus.validItemsCount > prevValidCountRef.current) {
      soundEffects.comboStepNote(comboStatus.validItemsCount);
    }
    prevValidCountRef.current = comboStatus.validItemsCount;
  }, [comboStatus.validItemsCount]);

  const handleAddRow = () => {
    soundEffects.tactileClick();
    setItems((prev) => {
      const next = [...prev, { item_name: "", quantity: 1, unit_price: 0 }];
      setActiveRowIdx(next.length - 1);
      return next;
    });
  };

  const handleRemoveRow = (idx: number) => {
    soundEffects.tactileClick();
    setItems((prev) => prev.filter((_, i) => i !== idx));
    setActiveRowIdx(0);
  };

  const handleItemChange = (
    idx: number,
    field: "item_name" | "quantity" | "unit_price",
    val: string | number
  ) => {
    setActiveRowIdx(idx);
    setItems((prev) =>
      prev.map((row, i) => (i === idx ? { ...row, [field]: val } : row))
    );
  };

  const handleAddPriceChipToActiveRow = (chipValue: number) => {
    soundEffects.tactileClick();
    if (inputMode === "detailed" && txType === "expense") {
      const targetIdx = Math.min(activeRowIdx, items.length - 1);
      setItems((prev) =>
        prev.map((row, i) =>
          i === targetIdx
            ? { ...row, unit_price: (Number(row.unit_price) || 0) + chipValue }
            : row
        )
      );
    } else {
      const curr = Number(quickAmount.replace(/\D/g, "")) || 0;
      setQuickAmount(String(curr + chipValue));
    }
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();

    const finalAmount =
      inputMode === "detailed" && txType === "expense"
        ? itemizedTotal
        : Number(quickAmount.replace(/\D/g, "")) || 0;

    if (finalAmount <= 0) return;

    const selectedExpCat = EXPENSE_CATEGORIES.find((c) => c.name === category);
    const needOrWant =
      txType === "income" ? "income" : selectedExpCat?.group || "want";

    const finalTitle =
      inputMode === "detailed" && txType === "expense"
        ? customTitle.trim() || autoGeneratedTitle
        : customTitle.trim() || category;

    const result = addTransaction({
      type: txType,
      category,
      need_or_want: needOrWant,
      title: finalTitle,
      total_amount: finalAmount,
      items:
        inputMode === "detailed" && txType === "expense" ? items : undefined,
    });

    if (result.isCombo) {
      soundEffects.comboFanfare();
      fireCozyConfetti("combo");
    } else {
      soundEffects.coinChime();
      fireCozyConfetti("normal");
    }

    setCustomTitle("");
    setQuickAmount("");
    setSmartSplitInput("");
    setTransactionDrawerOpen(false);
  };

  const comboTierLabel =
    comboStatus.validItemsCount >= 2
      ? `JURNAL RINCI AKTIF! +${comboStatus.pointsPreview} Poin & +${comboStatus.xpPreview} XP`
      : `Rincian ${comboStatus.validItemsCount}/2 menuju Jurnal Rinci (+10 Poin)`;

  const livePetMood: PetMood = comboStatus.isValidCombo ? "proud" : "happy";

  const finalTotalPreview =
    inputMode === "detailed" && txType === "expense"
      ? itemizedTotal
      : Number(quickAmount.replace(/\D/g, "")) || 0;

  return (
    <>
      <Drawer.Root
        open={isTransactionDrawerOpen}
        onOpenChange={setTransactionDrawerOpen}
      >
        <Drawer.Portal>
          <Drawer.Overlay className="fixed inset-0 bg-[#3D352E]/50 z-50 backdrop-blur-[2px]" />
          <Drawer.Content
            className={cn(
              "bg-[#FFFDF9] border-2 border-[#E6DFD2] border-b-[5px] border-b-[#D4C9B4] z-50 flex flex-col focus:outline-none",
              // Mobile (< 768px): Bottom Sheet max-h-[90dvh]
              "fixed bottom-0 left-0 right-0 rounded-t-[32px] max-h-[90dvh]",
              // Desktop (>= 768px): Centered Cozy Modal 2-Kolom max-w-3xl rounded-3xl
              "md:inset-x-auto md:left-1/2 md:top-1/2 md:bottom-auto md:-translate-x-1/2 md:-translate-y-1/2 md:after:hidden! md:w-[94vw] md:max-w-3xl md:rounded-3xl md:max-h-[88dvh] md:shadow-2xl"
            )}
          >
            {/* Mobile Drag Handle */}
            <div className="md:hidden mx-auto w-14 h-2 rounded-full bg-[#D4C9B4] my-2.5 shrink-0" />

            {/* Top Modal Header */}
            <div className="px-4 sm:px-6 py-3.5 border-b-2 border-[#E6DFD2] flex flex-wrap items-center justify-between gap-2 shrink-0 bg-white md:rounded-t-3xl">
              <div className="flex items-center gap-2.5 min-w-0">
                <CozyIcon name="plus_record" size={30} className="shrink-0" />
                <div className="min-w-0">
                  <Drawer.Title className="font-display text-lg sm:text-xl font-extrabold text-[#3D352E] leading-snug break-words">
                    Catat Jurnal Kas ({userProfile.display_name})
                  </Drawer.Title>
                  <Drawer.Description className="text-xs font-bold text-[#7A6E65] leading-snug break-words">
                    Total otomatis dihitung • Maks. 3 transaksi berpoin per hari
                  </Drawer.Description>
                </div>
              </div>

              <div className="flex items-center gap-2">
                <button
                  type="button"
                  onClick={() => setTransactionDrawerOpen(false)}
                  className="p-2 rounded-2xl border-2 border-[#E6DFD2] border-b-[3px] border-b-[#D4C9B4] bg-[#F7F3EB] hover:bg-[#EFE9DC] transition-colors cursor-pointer"
                >
                  <X className="w-4 h-4 text-[#3D352E]" />
                </button>
              </div>
            </div>

            {/* Body: 2 Columns on Desktop, Stacked on Mobile */}
            <form
              onSubmit={handleSubmit}
              className="p-4 sm:p-6 overflow-y-auto flex-1 min-h-0"
            >
              <div className="grid grid-cols-1 md:grid-cols-12 gap-5 items-start">
                {/* KOLOM KIRI (7 cols on Desktop): Input Controls */}
                <div className="md:col-span-7 space-y-4 min-w-0">
                  {/* 1. Pemilihan Jenis: Pengeluaran vs Pemasukan */}
                  <div className="grid grid-cols-2 gap-2 bg-[#F7F3EB] p-1.5 rounded-2xl border-2 border-[#E6DFD2]">
                    <button
                      type="button"
                      onClick={() => {
                        soundEffects.tactileClick();
                        setTxType("expense");
                        setCategory(EXPENSE_CATEGORIES[0].name);
                      }}
                      className={cn(
                        "py-2 px-3 rounded-xl font-display text-xs sm:text-sm font-extrabold transition-all cursor-pointer flex items-center justify-center gap-1.5",
                        txType === "expense"
                          ? "bg-[#FF8B7B] text-[#3D352E] border-b-[3px] border-b-[#E06353]"
                          : "text-[#7A6E65] hover:text-[#3D352E]"
                      )}
                    >
                      <CozyIcon name="cat_snack" size={18} />
                      <span>Pengeluaran (-Rp)</span>
                    </button>
                    <button
                      type="button"
                      onClick={() => {
                        soundEffects.tactileClick();
                        setTxType("income");
                        setCategory(INCOME_CATEGORIES[0].name);
                      }}
                      className={cn(
                        "py-2 px-3 rounded-xl font-display text-xs sm:text-sm font-extrabold transition-all cursor-pointer flex items-center justify-center gap-1.5",
                        txType === "income"
                          ? "bg-[#58CC02] text-white border-b-[3px] border-b-[#46A302]"
                          : "text-[#7A6E65] hover:text-[#3D352E]"
                      )}
                    >
                      <CozyIcon name="cat_income" size={18} />
                      <span>Pemasukan (+Rp)</span>
                    </button>
                  </div>

                  {/* 2. Mode Input Switcher: Jurnal Rinci (+10 Poin & +20 XP) vs Catat Kilat (+5 Poin & +10 XP) */}
                  {txType === "expense" && (
                    <div className="grid grid-cols-2 gap-2">
                      <button
                        type="button"
                        onClick={() => {
                          soundEffects.tactileClick();
                          setInputMode("detailed");
                        }}
                        className={cn(
                          "p-3 rounded-2xl text-left transition-all cursor-pointer border-2 min-w-0",
                          inputMode === "detailed"
                            ? "bg-white border-[#38B6FF] border-b-[4px] border-b-[#1E88E5]"
                            : "bg-[#F7F3EB] border-[#E6DFD2] opacity-80"
                        )}
                      >
                        <div className="flex items-center justify-between gap-1">
                          <span className="font-display text-xs sm:text-sm font-extrabold text-[#3D352E] flex items-center gap-1 truncate">
                            <CozyIcon name="combo_sparkle" size={16} animated />
                            Jurnal Rinci
                          </span>
                          <span className="text-[10px] font-display font-extrabold px-2 py-0.5 rounded-lg bg-[#FFC800] text-[#4A3500] shrink-0">
                            +10 Poin
                          </span>
                        </div>
                        <p className="text-[11px] font-bold text-[#7A6E65] mt-0.5 truncate">
                          Otomatis hitung total (+20 XP)
                        </p>
                      </button>

                      <button
                        type="button"
                        onClick={() => {
                          soundEffects.tactileClick();
                          setInputMode("quick");
                        }}
                        className={cn(
                          "p-3 rounded-2xl text-left transition-all cursor-pointer border-2 min-w-0",
                          inputMode === "quick"
                            ? "bg-white border-[#38B6FF] border-b-[4px] border-b-[#1E88E5]"
                            : "bg-[#F7F3EB] border-[#E6DFD2] opacity-80"
                        )}
                      >
                        <div className="flex items-center justify-between gap-1">
                          <span className="font-display text-xs sm:text-sm font-extrabold text-[#3D352E] flex items-center gap-1 truncate">
                            <CozyIcon name="xp_star" size={16} />
                            Catat Biasa
                          </span>
                          <span className="text-[10px] font-display font-extrabold px-2 py-0.5 rounded-lg bg-[#E6DFD2] text-[#3D352E] shrink-0">
                            +5 Poin
                          </span>
                        </div>
                        <p className="text-[11px] font-bold text-[#7A6E65] mt-0.5 truncate">
                          Input angka langsung (+10 XP)
                        </p>
                      </button>
                    </div>
                  )}

                  {/* 3. Input Item / Nominal */}
                  {txType === "expense" && inputMode === "detailed" ? (
                    <div className="space-y-3">
                      {/* One-line Smart Quick-Split Input */}
                      <div className="p-3 rounded-2xl bg-white border-2 border-[#E6DFD2] space-y-2">
                        <label className="text-xs font-display font-extrabold text-[#3D352E] flex items-center gap-1.5">
                          <CozyIcon name="combo_sparkle" size={16} />
                          Ketik Sekaligus (Pecah Otomatis)
                        </label>
                        <input
                          type="text"
                          value={smartSplitInput}
                          onChange={(e) =>
                            handleApplySmartSplit(e.target.value)
                          }
                          placeholder="Contoh: Nasi Goreng 18k, Es Teh 5k"
                          className="w-full px-3 py-2 rounded-xl border-2 border-[#E6DFD2] bg-[#F7F3EB] text-xs sm:text-sm font-bold text-[#3D352E] focus:outline-none focus:bg-white"
                        />
                        <ChipScroller label="Contoh rincian cepat">
                          {[
                            "Nasi Goreng 18k, Es Teh 5k",
                            "Ayam Bakar 20k, Air Mineral 5k, Kerupuk 3k",
                          ].map((preset) => (
                            <button
                              key={preset}
                              type="button"
                              onClick={() => handleApplySmartSplit(preset)}
                              className="text-[10px] font-display font-extrabold px-2 py-0.5 rounded-lg bg-[#F7F3EB] border border-[#E6DFD2] hover:bg-[#FFFBEB] cursor-pointer text-[#3D352E]"
                            >
                              {preset}
                            </button>
                          ))}
                        </ChipScroller>
                      </div>

                      {/* Itemized Rows */}
                      <div className="space-y-2">
                        <div className="flex items-center justify-between">
                          <span className="text-xs font-display font-extrabold uppercase tracking-wider text-[#7A6E65]">
                            Daftar Barang ({items.length} Item)
                          </span>
                          <button
                            type="button"
                            onClick={handleAddRow}
                            className="text-xs font-display font-extrabold text-[#3D352E] bg-[#F7F3EB] px-2.5 py-1 rounded-xl border-2 border-[#E6DFD2] border-b-[3px] border-b-[#D4C9B4] inline-flex items-center gap-1 hover:bg-white cursor-pointer"
                          >
                            <CozyIcon name="plus_record" size={14} /> + Tambah
                            Barang
                          </button>
                        </div>

                        <div className="space-y-2 max-h-[210px] overflow-y-auto pr-1">
                          {items.map((item, idx) => (
                            <div
                              key={idx}
                              onClick={() => setActiveRowIdx(idx)}
                              className={cn(
                                "flex items-center gap-2 p-2 rounded-2xl border-2 transition-colors",
                                activeRowIdx === idx
                                  ? "bg-white border-[#38B6FF]"
                                  : "bg-white border-[#E6DFD2]"
                              )}
                            >
                              <input
                                type="text"
                                value={item.item_name}
                                onChange={(e) =>
                                  handleItemChange(
                                    idx,
                                    "item_name",
                                    e.target.value
                                  )
                                }
                                placeholder={`Barang #${idx + 1} (cth: Nasi Goreng)`}
                                className="flex-1 min-w-0 px-2.5 py-1.5 rounded-xl bg-[#F7F3EB] text-xs sm:text-sm font-bold text-[#3D352E] focus:outline-none"
                              />
                              <div className="flex items-center gap-1 shrink-0">
                                <span className="text-xs font-display font-extrabold text-[#7A6E65]">
                                  Rp
                                </span>
                                <input
                                  type="number"
                                  value={item.unit_price || ""}
                                  onChange={(e) =>
                                    handleItemChange(
                                      idx,
                                      "unit_price",
                                      Number(e.target.value)
                                    )
                                  }
                                  placeholder="18000"
                                  className="w-24 px-2.5 py-1.5 rounded-xl bg-[#F7F3EB] font-display font-extrabold tabular-nums text-xs sm:text-sm text-[#3D352E] focus:outline-none"
                                />
                              </div>
                              {items.length > 1 && (
                                <button
                                  type="button"
                                  onClick={() => handleRemoveRow(idx)}
                                  className="p-1.5 rounded-xl bg-[#FFF2F0] text-[#E06353] border border-[#FFCDC6] hover:bg-[#FF8B7B] hover:text-[#3D352E] cursor-pointer"
                                >
                                  <Trash2 className="w-4 h-4" />
                                </button>
                              )}
                            </div>
                          ))}
                        </div>

                        {/* Quick Price Chips for Active Item */}
                        <ChipScroller label="Tambah nominal cepat barang" className="pt-1">
                          <span className="text-[11px] font-bold text-[#7A6E65]">
                            Tambah ke Barang #{activeRowIdx + 1}:
                          </span>
                          {QUICK_PRICE_CHIPS.map((chip) => (
                            <button
                              key={chip}
                              type="button"
                              onClick={() =>
                                handleAddPriceChipToActiveRow(chip)
                              }
                              className="px-2.5 py-1 rounded-xl bg-[#F7F3EB] hover:bg-white border border-[#E6DFD2] border-b-[2px] border-b-[#D4C9B4] font-display font-extrabold tabular-nums text-xs text-[#3D352E] cursor-pointer"
                            >
                              +{formatCompactRupiah(chip, { withPrefix: false })}
                            </button>
                          ))}
                        </ChipScroller>
                      </div>
                    </div>
                  ) : (
                    /* Mode Catat Kilat / Pemasukan */
                    <div className="space-y-3">
                      <div>
                        <label className="block text-xs font-display font-extrabold uppercase tracking-wider text-[#7A6E65] mb-1.5">
                          Nominal Total (Rupiah)
                        </label>
                        <div className="relative">
                          <span className="absolute left-4 top-1/2 -translate-y-1/2 font-display font-extrabold text-[#7A6E65]">
                            Rp
                          </span>
                          <input
                            type="number"
                            value={quickAmount}
                            onChange={(e) => setQuickAmount(e.target.value)}
                            placeholder="25000"
                            className="w-full pl-11 pr-4 py-3 rounded-2xl border-2 border-[#E6DFD2] bg-white font-display font-extrabold tabular-nums text-xl text-[#3D352E] focus:outline-none focus:border-[#38B6FF]"
                          />
                        </div>
                        <ChipScroller label="Nominal cepat" className="mt-2">
                          {QUICK_PRICE_CHIPS.map((chip) => (
                            <button
                              key={chip}
                              type="button"
                              onClick={() =>
                                handleAddPriceChipToActiveRow(chip)
                              }
                              className="px-3 py-1 rounded-xl border border-[#E6DFD2] border-b-[2px] border-b-[#D4C9B4] bg-[#F7F3EB] hover:bg-white font-display font-extrabold tabular-nums text-xs text-[#3D352E] cursor-pointer"
                            >
                              +{formatCompactRupiah(chip, { withPrefix: false })}
                            </button>
                          ))}
                        </ChipScroller>
                      </div>

                      <div>
                        <label className="block text-xs font-display font-extrabold uppercase tracking-wider text-[#7A6E65] mb-1">
                          Keterangan Singkat
                        </label>
                        <input
                          type="text"
                          value={customTitle}
                          onChange={(e) => setCustomTitle(e.target.value)}
                          placeholder={
                            txType === "expense"
                              ? "Contoh: Makan Siang / Beli Buku"
                              : "Contoh: Uang Saku Mingguan"
                          }
                          className="w-full px-3.5 py-2.5 rounded-2xl border-2 border-[#E6DFD2] bg-white font-bold text-sm focus:outline-none"
                        />
                      </div>
                    </div>
                  )}

                  {/* 4. Pilihan Kategori (Neutral buttons with semantic selected state) */}
                  <div>
                    <label className="block text-xs font-display font-extrabold uppercase tracking-wider text-[#7A6E65] mb-1.5">
                      Pilih Kategori
                    </label>
                    <ChipScroller label="Pilih kategori" watch={category}>
                      {(txType === "expense"
                        ? EXPENSE_CATEGORIES
                        : INCOME_CATEGORIES
                      ).map((cat) => {
                        const isSelected = category === cat.name;
                        return (
                          <button
                            key={cat.name}
                            type="button"
                            onClick={() => {
                              soundEffects.tactileClick();
                              setCategory(cat.name);
                            }}
                            className={cn(
                              "px-2.5 py-1.5 rounded-xl text-xs font-display font-extrabold flex items-center gap-1.5 transition-all cursor-pointer",
                              isSelected
                                ? "bg-[#38B6FF] text-white border-b-[3px] border-b-[#1E88E5]"
                                : "bg-[#F7F3EB] text-[#3D352E] border border-[#E6DFD2] hover:bg-white"
                            )}
                          >
                            <CategoryIcon category={cat.name} size={18} />
                            <span>{cat.name}</span>
                          </button>
                        );
                      })}
                    </ChipScroller>
                  </div>
                </div>

                {/* KOLOM KANAN (5 cols on Desktop) / Sticky Preview on Mobile: Live Struk Kas Digital + Mini Pet + Combo Meter */}
                <div className="md:col-span-5 space-y-3.5 min-w-0">
                  {/* Live Struk Kas Digital Card */}
                  <div className="rounded-3xl bg-white border-2 border-[#E6DFD2] border-b-[4px] border-b-[#D4C9B4] p-4 space-y-3">
                    {/* Mini Pet Companion Reaction */}
                    <div className="flex items-center gap-3 bg-[#F7F3EB] rounded-2xl p-2.5 border border-[#E6DFD2]">
                      <div className="w-14 h-16 rounded-2xl bg-white border border-[#E6DFD2] flex items-center justify-center shrink-0">
                        <CustomizablePetAvatar
                          species={userProfile.activeSpecies || "chubby_cat"}
                          stage={currentStage}
                          mood={livePetMood}
                          customName={petName}
                          equippedAccessories={userProfile.equippedAccessories}
                          className="w-13 h-15"
                        />
                      </div>
                      <div className="min-w-0">
                        <p className="text-[11px] font-display font-extrabold uppercase text-[#7A6E65] leading-snug break-words">
                          {petName} • {GROWTH_STAGE_META[currentStage].name}
                        </p>
                        <p className="text-xs font-bold text-[#3D352E] leading-snug break-words">
                          {comboStatus.isValidCombo
                            ? "Wah rincianmu jujur & lengkap! +10 Poin & +20 Stage XP siap masuk!"
                            : "Ketik rincian minimal 2 barang buat dapat +10 Poin & +20 Stage XP!"}
                        </p>
                      </div>
                    </div>

                    {/* Animated Combo Meter Bar */}
                    {txType === "expense" && inputMode === "detailed" && (
                      <motion.div
                        key={comboStatus.validItemsCount}
                        initial={{ scale: comboStatus.isValidCombo ? 0.96 : 1 }}
                        animate={{ scale: 1 }}
                        transition={{
                          type: "spring",
                          stiffness: 400,
                          damping: 18,
                        }}
                        className="p-3 rounded-2xl bg-[#FFFBEB] border-2 border-[#FDE08D] space-y-1.5"
                      >
                        <div className="flex items-center justify-between gap-1">
                          <span className="font-display text-xs font-extrabold text-[#4A3500] truncate">
                            {comboTierLabel}
                          </span>
                          <span className="font-display font-extrabold tabular-nums text-[11px] px-2 py-0.5 rounded-lg bg-[#FFC800] text-[#4A3500] shrink-0">
                            +{comboStatus.pointsPreview} Poin
                          </span>
                        </div>
                        <ChunkyProgressBar
                          value={Math.min(2, comboStatus.validItemsCount)}
                          max={2}
                          variant={
                            comboStatus.isValidCombo ? "honey" : "sky"
                          }
                        />
                      </motion.div>
                    )}

                    {/* Live Digital Receipt Breakdown */}
                    <div className="border-t-2 border-dashed border-[#E6DFD2] pt-3 space-y-2">
                      <div className="flex items-center justify-between text-xs font-bold text-[#7A6E65]">
                        <span>Pratinjau Struk Kas</span>
                        <span className="truncate max-w-[140px]">
                          {category}
                        </span>
                      </div>

                      <p className="font-display text-sm font-extrabold text-[#3D352E] truncate">
                        {txType === "expense" && inputMode === "detailed"
                          ? autoGeneratedTitle
                          : customTitle.trim() || category}
                      </p>

                      {txType === "expense" && inputMode === "detailed" && (
                        <div className="space-y-1 max-h-[110px] overflow-y-auto pr-1">
                          {items
                            .filter((i) => i.item_name.trim() || i.unit_price > 0)
                            .map((it, idx) => (
                              <div
                                key={idx}
                                className="flex items-center justify-between text-xs font-bold text-[#7A6E65]"
                              >
                                <span className="truncate pr-2">
                                  • {it.item_name || `Barang #${idx + 1}`}
                                </span>
                                <span className="font-display font-extrabold tabular-nums text-[#3D352E] shrink-0">
                                  {formatRupiah(Number(it.unit_price) || 0)}
                                </span>
                              </div>
                            ))}
                        </div>
                      )}

                      <div className="pt-2 border-t border-[#E6DFD2] flex items-center justify-between gap-2 flex-wrap">
                        <span className="text-xs font-display font-extrabold text-[#7A6E65]">
                          Total Otomatis:
                        </span>
                        <span
                          className={cn(
                            "font-display text-lg font-extrabold tabular-nums break-words",
                            txType === "income"
                              ? "text-[#46A302]"
                              : "text-[#E06353]"
                          )}
                        >
                          {txType === "income" ? "+" : "-"}
                          {formatRupiah(finalTotalPreview)}
                        </span>
                      </div>
                    </div>
                  </div>

                  {/* Primary Submit CTA (Matcha Green Exclusive) */}
                  <TactileButton
                    type="submit"
                    variant="matcha"
                    size="lg"
                    fullWidth
                    disabled={finalTotalPreview <= 0}
                  >
                    <CozyIcon name="check_badge" size={22} />
                    <span>
                      Simpan Catatan ({formatRupiah(finalTotalPreview)})
                    </span>
                    <span className="px-2 py-0.5 rounded-xl bg-[#FFC800] text-[#4A3500] text-xs font-display font-extrabold shrink-0">
                      +{comboStatus.pointsPreview} Poin
                    </span>
                  </TactileButton>
                </div>
              </div>
            </form>
          </Drawer.Content>
        </Drawer.Portal>
      </Drawer.Root>
    </>
  );
}
